from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from reportlab.lib.units import inch
from django.utils import timezone




def generate_outstanding_report_pdf(
    data,
    filename
):

    document = SimpleDocTemplate(
        filename,
        pagesize=A4,
    )


    styles = getSampleStyleSheet()

    elements = []


    # ==========================
    # HEADER
    # ==========================

    elements.append(
        Paragraph(
            "CAMPUSPAY ENTERPRISE",
            styles["Title"]
        )
    )


    elements.append(
        Paragraph(
            "Outstanding Fees Report",
            styles["Heading2"]
        )
    )


    elements.append(
        Spacer(
            1,
            20
        )
    )


    elements.append(
        Paragraph(
            f"Generated: {timezone.now().date()}",
            styles["Normal"]
        )
    )


    elements.append(
        Spacer(
            1,
            20
        )
    )



    # ==========================
    # SUMMARY
    # ==========================

    summary = [

        [
            "Total Expected",
            f"GHS {data['total_expected']}"
        ],

        [
            "Total Paid",
            f"GHS {data['total_paid']}"
        ],

        [
            "Outstanding",
            f"GHS {data['total_outstanding']}"
        ],

    ]


    summary_table = Table(
        summary,
        colWidths=[
            2*inch,
            2*inch
        ]
    )


    summary_table.setStyle(
        TableStyle(
            [

                (
                    "GRID",
                    (0,0),
                    (-1,-1),
                    0.5,
                    colors.black
                ),

                (
                    "BACKGROUND",
                    (0,0),
                    (-1,0),
                    colors.lightgrey
                ),

            ]
        )
    )


    elements.append(
        summary_table
    )


    elements.append(
        Spacer(
            1,
            25
        )
    )



    # ==========================
    # REPORT TABLE
    # ==========================


    table_data = [

        [

            "Student ID",

            "Name",

            "Department",

            "Level",

            "Expected",

            "Paid",

            "Balance",

            "Status",

        ]

    ]


    for item in data["report"]:


        table_data.append(

            [

                item["member"].student_id,

                item["member"].first_name,

                str(
                    item["member"].department
                ),

                item["member"].level,

                f"GHS {item["expected"]}",

                f"GHS {item["paid"]}",

                f"GHS {item["balance"]}",

                item["status"],

            ]

        )



    report_table = Table(
        table_data,
        repeatRows=1,
    )


    report_table.setStyle(

        TableStyle(

            [

                (
                    "GRID",
                    (0,0),
                    (-1,-1),
                    0.25,
                    colors.black
                ),

                (
                    "BACKGROUND",
                    (0,0),
                    (-1,0),
                    colors.darkblue
                ),

                (
                    "TEXTCOLOR",
                    (0,0),
                    (-1,0),
                    colors.white
                ),

            ]

        )

    )


    elements.append(
        report_table
    )


    elements.append(
        Spacer(
            1,
            20
        )
    )


    elements.append(

        Paragraph(

            "Generated by CampusPay Enterprise",

            styles["Italic"]

        )

    )


    document.build(
        elements
    )